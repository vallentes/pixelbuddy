export function supported(text: string): boolean {
  return [...text.toUpperCase()].every((c) => c in G);
}

/** Width in font pixels (5 per glyph + 1 spacing). */
export function measure(text: string): number {
  return Math.max(0, [...text].length * 6 - 1);
}

export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, px: number, color: string) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const rows = G[ch] ?? G['?'];
    rows.forEach((bits, ry) => {
      for (let bx = 0; bx < 5; bx++) {
        if (bits & (0x10 >> bx)) ctx.fillRect(cx + bx * px, y + ry * px, px, px);
      }
    });
    cx += 6 * px;
  }
}
